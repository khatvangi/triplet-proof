"""build REPORT.md from RESULTS.json (safe to rerun on a partial RESULTS.json)."""
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
R = json.load(open(os.path.join(HERE, "RESULTS.json")))


def fmt(x, n=6):
    return f"{x:.{n}f}"


def hitStr(row):
    s = f"{row['random']['hits']}/{row['random']['restarts']}"
    for k, v in row.get("warm", {}).items():
        s += f"; {k.replace('n3_neighbour', 'nbr')} {v['hits']}/{v['restarts']}"
    return s


def n2Row(usage, w):
    return next(r for r in R["n2"] if r["usage"] == usage and tuple(r["w"]) == tuple(w))


def table(usage, hyp):
    rows = [r for r in R["n3"] if r["usage"] == usage]
    if not rows:
        return f"_no {usage} cells completed_\n"
    key = "H_inv" if hyp == "inv" else "H_term"
    out = ["| r1 | r3 | doublet w | best Dpos n=2 | n=2 hits | best Dpos n=3 | n=3 hits (random; warm by source) "
           "| A = 1 - D3/D2 | pos-3 syn (raw / usage-wt) | SGC Dpos | SGC excess over n=3 opt |"
           + (" certified |" if hyp == "inv" else ""),
           "|---" * (11 + (hyp == "inv")) + "|"]
    for r in rows:
        h = r[key]
        w2 = (r["r1"], 1.0) if hyp == "inv" else (r["r1"], r["r3"])
        n2 = n2Row(usage, w2)
        cert = (" " + ("yes" if h["certified"] else "**SEARCH FAILURE**")
                + ("" if h["random_only_certified"] else " (warm only)") + " |") if hyp == "inv" else ""
        cut = " (cut)" if r.get("restarts_cut") else ""
        out.append(f"| {r['r1']:g} | {r['r3']:g} | ({w2[0]:g}, {w2[1]:g}) | {fmt(h['D2'])} | {hitStr(n2)} | "
                   f"{fmt(h['D3'])} | {hitStr(r)}{cut} | {h['A']:+.4f} | "
                   f"{r['pos3_synonymy']['raw']:.3f} / {r['pos3_synonymy']['usage_weighted']:.3f} | "
                   f"{fmt(r['sgc']['Dpos'])} | {fmt(r['sgc']['excess'], 4)} ({r['sgc']['excess_percent']:.1f}%) |{cert}")
    return "\n".join(out) + "\n"


gA = R["gateA"]
L = ["# Position-weighted doublet-vs-triplet optima", "",
     "Generated by `make_report.py` from `RESULTS.json` (search: `position_model.py`, log: `run.log`).", "",
     "## Metric", "",
     "Dpos = sum_a f_a (1/n_a) sum_{c in block(a)} sum_p w_p sum_{c' differs from c only at p, c' sense} "
     "dist(a, label(c')). RAA10 classes, representatives, class vectors and U/P usage are identical to "
     f"`usage_cert` (Swiss-Prot {R['proteome']['release']}, {R['proteome']['date']}). "
     "Weights w = (r1, 1, r3). Optimisation: k = 10, class sizes free (every class >= 1 codon), "
     "no stop codons (16 doublets / 64 triplets all sense).", "",
     "**Decoder hypotheses.** No doublet decoder exists, so the doublet weights are an **assumption**:", "",
     "- **H-inv** (decoder-invariant positions): doublet (w1, w2), triplet (w1, w2, w3).",
     "- **H-term** (the terminal base is the sloppy one): doublet (w1, w3), triplet (w1, w2, w3).", "",
     "The triplet weights are the same under both hypotheses, so the n=3 optimum in each row is shared "
     "and only D2 (and hence A) differs between the two tables. At r3 = 1 the hypotheses coincide.", "",
     "## Gates", "",
     f"- **Gate A** (w = 1 reproduces usage_cert Dw to 1e-9, both via the imported usage_cert kernel and the "
     f"values stored in usage_cert/RESULTS.json): **{'PASS' if gA['pass'] else 'FAIL'}**"]
for k, v in gA.items():
    if k != "pass":
        L.append(f"  - {k}: Dpos(w=1) = {v['Dpos_w1']:.12f}, max |diff| = {v['absdiff_max']:.1e}")
L += [f"- **Gate B** (weighted kernel vs brute-force definition at random weights/labelings/usage, "
      f"{R['gateB']['n_cases']} cases; incremental recolor/swap vs full recompute, {R['gateB']['n_incremental']} cases): "
      f"max rel diff {R['gateB']['max_reldiff_brute']:.1e} / {R['gateB']['max_reldiff_incremental']:.1e}: "
      f"**{'PASS' if R['gateB']['pass'] else 'FAIL'}**",
      f"- **Gate C** (under H-inv weights the silent lift L3(xyz) = L2(xy) is exact, 100 random labelings, "
      f"random w1, w3, random usage): max rel diff {R['gateC']['max_reldiff']:.1e}: "
      f"**{'PASS' if R['gateC']['pass'] else 'FAIL'}**", ""]

# cross-checks against usage_cert at w = 1
ck = []
for usage, d2ref, d3ref in (("U", 20.017516292, 20.017516292), ("P", 18.835846661, 18.766672019)):
    try:
        n2 = n2Row(usage, (1.0, 1.0))["best"]
        n3 = next(r for r in R["n3"] if r["usage"] == usage and r["r1"] == 1 and r["r3"] == 1)["best"]
        ck.append(f"- {usage}, w = (1,1,1): n=2 best {n2:.9f} (usage_cert R{'2' if usage == 'U' else '3'}: {d2ref}), "
                  f"n=3 best {n3:.9f} (usage_cert: {d3ref})")
    except StopIteration:
        pass
if ck:
    L += ["Cross-check against the independent usage_cert search at uniform weights:", ""] + ck + [""]

L += ["## Results", "",
      "A > 0 means the best triplet code beats the best doublet code. Hits = restarts reaching the best "
      "value (relative tolerance 1e-9); warm sources for n=3 are lift_Hinv (lift of the best H-inv doublet), "
      "lift_Hterm (lift of the best H-term doublet) and nbr (best n=3 code at the preceding weight setting). "
      "Position-3 synonymy is the fraction of position-3 arcs of the best n=3 code that stay in the same "
      "class (raw count, and weighted by f_a/n_a of the source class). SGC = 10-class projection of the "
      "standard code on its 61 sense codons, scored with the triplet weights.", ""]
for usage in ("U", "P"):
    L += [f"### Usage {usage}, H-inv", "", table(usage, "inv"), f"### Usage {usage}, H-term", "", table(usage, "term")]

# silent-position check: any triplet code that is silent at one position p is a lifted doublet on the
# other two positions, so D3* <= min_p D2*(w without p). doublet Dpos is symmetric under swapping its two
# positions, so every pair's optimum is already in the n=2 grid as (max(pair), min(pair)) or (r1, x).
def d2Pair(usage, a, b):
    for w in ((a, b), (b, a)):
        try:
            return n2Row(usage, w)["best"]
        except StopIteration:
            pass
    return None


sp = ["## Is the triplet optimum always one silent position?", "",
      "A triplet code that is fully synonymous at one position p is a lifted doublet on the other two, so "
      "D3* <= min_p D2*(pair without p). Every pair's doublet optimum is in the n=2 grid (doublet Dpos is "
      "symmetric under swapping positions): (w2,w3) = (1,r3) is the n=2 cell (1,r3), (w1,w3) = (r1,r3), "
      "(w1,w2) = (r1,1).", "",
      "| usage | w | D3* | min_p D2*(pair) | silenced position | D3* - bound |", "|---|---|---|---|---|---|"]
for r in R["n3"]:
    pairs = {"1": (1.0, r["r3"]), "2": (r["r1"], r["r3"]), "3": (r["r1"], 1.0)}
    vals = {p: d2Pair(r["usage"], *ab) for p, ab in pairs.items()}
    if any(v is None for v in vals.values()):
        continue
    pm = min(vals, key=vals.get)
    sp.append(f"| {r['usage']} | ({r['r1']:g},1,{r['r3']:g}) | {r['best']:.9f} | {vals[pm]:.9f} | {pm} | "
              f"{r['best'] - vals[pm]:+.2e} |")
L += sp + ["", "A negative last column means the triplet optimum beats every silent-position lift, so it uses all "
           "three positions non-trivially. Zero means the best triplet code found is a lifted doublet.", ""]

fails = [r for r in R["n3"] if r.get("SEARCH_FAILURE")]
L += [f"**Search failures (H-inv certification):** {len(fails)}", ""]

L += ["## Secondary: uniform weights, n=3 on 61 sense codons (UAA/UAG/UGA excluded)", ""]
if not R["secondary"]:
    L.append("_not run_")
for s in R["secondary"]:
    if "skipped" in s:
        L.append(f"- {s['usage']}: skipped ({s['skipped']})")
    else:
        L.append(f"- {s['usage']}: best Dw = {s['best']:.9f}, hits {hitStr(s)}; gap to the n=2 optimum "
                 f"{s['D2_best_usage_cert']} = {s['gap']:.6f} ({s['gap_percent']:.2f}%). "
                 f"usage_cert's earlier R4 value: {s['usage_cert_R4']:.9f}.")
L.append("")

red = R.get("reductions", [])
L += ["## Search budget and reductions", "",
      f"Per cell: {R['config']['N_RANDOM']} random restarts + {R['config']['N_WARM']} warm starts (n=2 cells after the "
      f"first in each r1 row warm-start from the neighbouring n=2 optimum; the first has none), SA of "
      f"{R['config']['n_iter_n2']} (n=2) / {R['config']['n_iter_n3']} (n=3) single-codon recolors, then steepest "
      f"descent over all recolors and swaps. Floors: {R['config']['floors'][0]} random + {R['config']['floors'][1]} warm.",
      "", ("Cells reduced to the floors: " + "; ".join(red)) if red else "No cell was reduced.",
      "", f"Elapsed: {R.get('elapsed_seconds', 0):.0f} s. Finished: {R.get('finished', False)}.", ""]

L += ["## Caveats", "",
      "1. **The doublet weights are an assumption.** No doublet decoder exists, so the error profile of a "
      "hypothetical doublet code is unknown. H-inv and H-term bracket two simple guesses. The sign and size of A "
      "depend on which one is chosen, and neither is measured.",
      "2. **H-inv certification is partly by construction.** The lift of the best H-inv doublet is itself a warm "
      "start, and descent from it cannot go up, so `certified` cannot fail unless the lift evaluation is wrong "
      "(gate C). The informative column is `random_only_certified`: whether random restarts alone reach the lift "
      "bound. Rows marked '(warm only)' failed that test.",
      "3. **Optima are heuristic.** They are the best of the restarts, not proved global optima. Hit counts give "
      "the evidence. A cell whose best was reached by only one source should be treated as an upper bound.",
      "4. **The SGC comparison is not like for like.** The optimum is searched over 64 all-sense triplets, while "
      "the SGC is scored on its 61 sense codons, where stop neighbours drop out of the sum. The secondary run "
      "(61 codons, w = 1) shows how much stop exclusion alone lowers the optimum.",
      "5. **Under H-term the lift of the best doublet is not an upper bound** on the n=3 optimum under triplet "
      "weights, because the lifted code's position-2 arcs carry weight 1, not r3. It is reported only as "
      "`lift_D3_under_triplet_weights` in RESULTS.json.",
      "6. **Position-3 synonymy is not identifiable when w3 equals w1 or w2.** Dpos is then symmetric under "
      "exchanging those positions, so optima tie with their position-permuted copies. At w = (1,1,1) the search "
      "can return a copy of the silent lift whose synonymous position is 1 or 2, which shows as pos-3 synonymy 0. "
      "Read the syn3 column only where r3 differs from both r1 and 1.",
      "7. Rates are applied as linear weights on arc costs. The actual misreading spectrum (transition/"
      "transversion bias, base-specific rates) is not modelled.",
      ""]
open(os.path.join(HERE, "REPORT.md"), "w").write("\n".join(L))
print("wrote REPORT.md")
